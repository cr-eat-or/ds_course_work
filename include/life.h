#ifndef LIFE_H
#define LIFE_H

#include "grid.h"

/*
 * Модуль эволюции: один дискретный шаг по правилу Конвея.
 *
 * Один шаг игры Жизнь Конвея (правило B3/S23).
 * Читается только src; результат записывается в dst.
 * Размеры src и dst должны совпадать; соседи за краем поля считаются мёртвыми
 * (через grid_get у границы).
 *
 * true при успехе, false при ошибке (NULL, несовпадение размеров).
 */
bool life_step(const Grid *src, Grid *dst);

#endif
